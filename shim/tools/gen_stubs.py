#!/usr/bin/env python3
"""Generate the shim's export stubs from the canonical .def.

Input : ../data/eos-proxy.def  (681 names, from the genuine SDK)
Output: src/exports.inc   one `EOS_STUB(name)` line per export
        src/exports.def   the same names as a local .def, so the folder builds
                          when copied somewhere else

The generated files are build artifacts: edit the canonical .def or this
script, never the output.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DLL_DIR = os.path.dirname(HERE)

IDENT = re.compile(r"^EOS_[A-Za-z0-9_]+$")

# Implemented by hand in src/abi/eos.cpp; must not also be generated.
SPECIAL = {
    # stage D
    "EOS_GetVersion",  # returns a version string; NULL here crashes the game
    # stage E1 - the calls the real game trail demands
    "EOS_Platform_Create",
    "EOS_Platform_Tick",
    "EOS_Platform_Release",
    "EOS_Platform_GetConnectInterface",
    "EOS_Platform_GetAuthInterface",
    "EOS_Platform_GetAntiCheatClientInterface",
    "EOS_Platform_GetRTCInterface",
    "EOS_RTC_GetAudioInterface",
    "EOS_Shutdown",
    "EOS_Connect_Login",
    "EOS_Connect_GetLoginStatus",
    "EOS_Connect_CopyIdToken",
    "EOS_Connect_IdToken_Release",
    "EOS_Connect_AddNotifyAuthExpiration",
    "EOS_ProductUserId_ToString",
    "EOS_ProductUserId_FromString",
    "EOS_ProductUserId_IsValid",
    "EOS_EpicAccountId_IsValid",
    "EOS_EResult_IsOperationComplete",
    "EOS_Auth_Login",
    "EOS_Auth_GetLoginStatus",
    "EOS_Auth_CopyUserAuthToken",
    "EOS_Auth_GetLoggedInAccountByIndex",
    "EOS_Auth_GetLoggedInAccountsCount",
    "EOS_Auth_Token_Release",
    "EOS_EpicAccountId_ToString",
    "EOS_EpicAccountId_FromString",
    "EOS_AntiCheatClient_BeginSession",
    "EOS_AntiCheatClient_EndSession",
    "EOS_AntiCheatClient_AddNotifyMessageToServer",
    "EOS_AntiCheatClient_RemoveNotifyMessageToServer",
}


def read_def(path: str) -> list[str]:
    names: list[str] = []
    seen: set[str] = set()
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.split(";", 1)[0].strip()
            if not line or line.upper() == "EXPORTS":
                continue
            name = line.split("=", 1)[0].strip()
            if not name:
                continue
            if not IDENT.match(name):
                sys.exit(f"bad export name in {path}: {name!r}")
            if name in seen:
                sys.exit(f"duplicate export in {path}: {name}")
            seen.add(name)
            names.append(name)
    return names


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--def", dest="def_path", default=os.path.join(
        DLL_DIR, "data", "eos-proxy.def"))
    ap.add_argument("--out-dir", default=os.path.join(DLL_DIR, "src"))
    args = ap.parse_args()

    names = read_def(os.path.abspath(args.def_path))
    generated = [n for n in names if n not in SPECIAL]
    skipped = [n for n in names if n in SPECIAL]

    inc_path = os.path.join(args.out_dir, "exports.inc")
    def_path = os.path.join(args.out_dir, "exports.def")

    with open(inc_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// generated by tools/gen_stubs.py - do not edit\n")
        fh.write(f"// {len(generated)} generated stubs, "
                 f"{len(skipped)} hand-written: {', '.join(skipped) or 'none'}\n")
        for n in generated:
            fh.write(f"EOS_STUB({n})\n")

    with open(def_path, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("; generated by tools/gen_stubs.py - do not edit\n")
        fh.write("EXPORTS\n")
        for n in names:
            fh.write(f"    {n}\n")

    print(f"def       {args.def_path} ({len(names)} names)")
    print(f"wrote     {inc_path} ({len(generated)} stubs)")
    print(f"wrote     {def_path} ({len(names)} exports)")
    if skipped:
        print(f"skipped   {', '.join(skipped)} (implemented in src/abi/eos.cpp)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
